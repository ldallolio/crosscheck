std::string flowFactsFormat(const Options& opts) {
  if (!opts.flowFactsFormat.empty()) return opts.flowFactsFormat;
  const std::string& p = opts.flowFactsPath;
  if (p.size() >= 4 && p.compare(p.size() - 4, 4, ".ais") == 0) return "ais2";
  return "ffx";
}

std::string toFlowFacts(const Report& report, const Options& opts) {
  bool program = opts.flowFactsContext == "program";
  Collected c = collect(report, program);
  std::vector<std::string> head = header(c, program, opts.entry);
  std::string fmt = flowFactsFormat(opts);
  if (fmt == "ais") return ais(c, head, false);
  if (fmt == "ais2") return ais(c, head, true);
  return ffx(c, head);
}

std::string toSarif(const Report& report, const Options& opts) {
  std::vector<std::string> results;
  for (const FunctionReport& f : report.functions) {
    std::string floc = location(f.file, f.line, 0, opts.sarifBase);
    for (const Site& s : f.errorSites)
      results.push_back(result(s.rule == "deadline" ? 1 : 0, f.name + ": " + s.message,
                               location(s.file.empty() ? f.file : s.file, s.line ? s.line : f.line,
                                        s.column, opts.sarifBase)));
    if (f.bounded) {
      std::string msg = "'" + f.name + "': worst-case cost bound " + std::to_string(f.wcet) + " units";
      if (f.wcetInContext) msg += ", " + std::to_string(*f.wcetInContext) + " in the program's calling contexts";
      if (f.deadline) msg += " (deadline " + std::to_string(*f.deadline) + ")";
      if (f.certificate == "emitted" && f.certificateBound)
        msg += "; cost certificate emitted, bound " + std::to_string(*f.certificateBound);
      if (!f.assumptions.empty()) msg += "; " + std::to_string(f.assumptions.size()) + " assumption(s)";
      std::string props = "\"wcet\": " + std::to_string(f.wcet);
      if (f.wcetInContext) props += ", \"wcetInContext\": " + std::to_string(*f.wcetInContext);
      if (f.deadline) props += ", \"deadline\": " + std::to_string(*f.deadline);
      if (f.certificateBound) props += ", \"certificateBound\": " + std::to_string(*f.certificateBound);
      results.push_back(result(2, msg, floc, props));
    }
    for (const std::string& a : f.assumptions) results.push_back(result(3, f.name + ": " + a, floc));
  }
  std::string out = "{\n  \"$schema\": \"https://json.schemastore.org/sarif-2.1.0.json\",\n"
                    "  \"version\": \"2.1.0\",\n  \"runs\": [{\n"
                    "    \"tool\": {\"driver\": {\"name\": \"CrossCheck\", \"version\": \"" CROSSCHECK_VERSION
                    "\", \"rules\": [";
  for (std::size_t i = 0; i < sizeof rules / sizeof rules[0]; ++i)
    out += std::string(i ? ", " : "") + "{\"id\": \"" + rules[i].id + "\", \"shortDescription\": {\"text\": " +
           jsonQuote(rules[i].text) + "}, \"defaultConfiguration\": {\"level\": \"" + rules[i].level + "\"}}";
  out += "]}},\n";
  if (!opts.sarifBase.empty()) {
    std::string b = opts.sarifBase;
    if (b.back() != '/') b += '/';
    bool rel = false;
    out += "    \"originalUriBaseIds\": {\"%SRCROOT%\": {\"uri\": " + jsonQuote(uriOf(b, "", rel)) + "}},\n";
  }
  out += "    \"results\": [";
  for (std::size_t i = 0; i < results.size(); ++i) out += (i ? ",\n      " : "\n      ") + results[i];
  out += results.empty() ? "]\n  }]\n}\n" : "\n    ]\n  }]\n}\n";
  return out;
}

