std::string xmlEscape(const std::string& s) {
  std::string out;
  for (char c : s) {
    switch (c) {
      case '&': out += "&amp;"; break;
      case '<': out += "&lt;"; break;
      case '>': out += "&gt;"; break;
      case '"': out += "&quot;"; break;
      case '\'': out += "&apos;"; break;
      default: out += c;
    }
  }
  return out;
}

/// Text that may stand inside an XML comment (no "--", no trailing "-").
std::string xmlComment(const std::string& s) {
  std::string out;
  for (char c : s) {
    if (c == '-' && !out.empty() && out.back() == '-') out += ' ';
    out += c;
  }
  if (!out.empty() && out.back() == '-') out += ' ';
  return out;
}

/// Text on one line of a `#` comment.
std::string oneLine(const std::string& s) {
  std::string out = s;
  std::replace(out.begin(), out.end(), '\n', ' ');
  return out;
}

std::string aisString(const std::string& s) {
  std::string out = "\"";
  for (char c : s) {
    if (c == '"' || c == '\\') out += '\\';
    out += c;
  }
  return out + "\"";
}

/// One exported loop: a source location and the largest bound over the reports
/// (and template instances) that contain it.
struct Fact {
  std::string file;
  unsigned line = 0, column = 0;
  std::uint64_t bound = 0;
  std::set<std::string> functions;  // qualified names
  std::string symbol;               // linker name of the first function (aiT)
  std::string potential;
  bool certified = true;            // every containing function has an emitted certificate
  unsigned index = 0;               // position among the loops of its function (1-based)
};

/// The bound to export for a loop, if any.
std::optional<std::uint64_t> exported(const LoopReport& l, bool program) {
  std::optional<std::uint64_t> b;
  if (l.verified) b = l.bound;
  if (program && l.inContext) b = b ? std::min(*b, *l.inContext) : *l.inContext;
  return b;
}

struct Collected {
  std::vector<Fact> facts;
  unsigned assumed = 0;    // loops whose bound is an annotation: not exported
  unsigned unbounded = 0;  // loops without a bound in the chosen mode
  std::set<std::string> assumptions;
};

Collected collect(const Report& report, bool program) {
  Collected out;
  std::map<std::tuple<std::string, unsigned, unsigned>, std::size_t> at;
  for (const FunctionReport& f : report.functions) {
    // Source order of the loops of this function (for aiT's per-routine numbering).
    std::vector<const LoopReport*> loops;
    for (const LoopReport& l : f.loops) loops.push_back(&l);
    std::stable_sort(loops.begin(), loops.end(), [](const LoopReport* a, const LoopReport* b) {
      return std::tie(a->file, a->line, a->column) < std::tie(b->file, b->line, b->column);
    });
    bool any = false;
    for (std::size_t i = 0; i < loops.size(); ++i) {
      const LoopReport& l = *loops[i];
      if (!l.verified && !(program && l.inContext)) {
        if (l.bound > 0) ++out.assumed;
        else ++out.unbounded;
        continue;
      }
      std::optional<std::uint64_t> b = exported(l, program);
      if (!b) { ++out.unbounded; continue; }
      any = true;
      auto key = std::make_tuple(l.file.empty() ? f.file : l.file, l.line, l.column);
      auto it = at.find(key);
      if (it == at.end()) {
        Fact x;
        std::tie(x.file, x.line, x.column) = key;
        x.bound = *b;
        x.symbol = f.symbol.empty() ? f.name : f.symbol;
        x.potential = l.potential;
        x.index = static_cast<unsigned>(i + 1);
        x.certified = f.certificate == "emitted";
        x.functions.insert(f.name);
        at[key] = out.facts.size();
        out.facts.push_back(std::move(x));
      } else {
        Fact& x = out.facts[it->second];
        x.bound = std::max(x.bound, *b);
        x.functions.insert(f.name);
        x.certified = x.certified && f.certificate == "emitted";
      }
    }
    if (any)
      for (const std::string& a : f.assumptions) out.assumptions.insert(f.name + ": " + a);
  }
  std::sort(out.facts.begin(), out.facts.end(), [](const Fact& a, const Fact& b) {
    return std::tie(a.file, a.line, a.column) < std::tie(b.file, b.line, b.column);
  });
  return out;
}

std::string join(const std::set<std::string>& s, const std::string& sep) {
  std::string out;
  for (const std::string& x : s) out += (out.empty() ? "" : sep) + x;
  return out;
}

std::vector<std::string> header(const Collected& c, bool program, const std::string& entry) {
  std::vector<std::string> h;
  h.push_back(std::string("Flow facts generated by CrossCheck ") + CROSSCHECK_VERSION + ".");
  h.push_back("Each bound is the maximal number of executions of the loop body per entry of the loop.");
  if (program)
    h.push_back("Bounds hold in the calling contexts of the analysed program (entry: " +
                (entry.empty() ? std::string("the functions that no analysed function calls") : entry) +
                "), not for other callers.");
  else
    h.push_back("Bounds hold for every call of the enclosing function that meets its preconditions.");
  h.push_back("They are derived by the analysis (ranking potentials checked by Z3); the analysis is not "
              "verified. A function marked certified also has a cost certificate (check it with "
              "crosscheck-check); the certificate bounds the cost, not each loop.");
  if (c.assumed)
    h.push_back(std::to_string(c.assumed) + " loop bound(s) stated by annotations are assumptions and are not exported.");
  if (c.unbounded) h.push_back(std::to_string(c.unbounded) + " loop(s) without a derived bound are not exported.");
  if (!c.assumptions.empty()) {
    h.push_back("Assumptions of the analysis (trusted, not proved):");
    for (const std::string& a : c.assumptions) h.push_back("  " + a);
  }
  return h;
}

std::string ffx(const Collected& c, const std::vector<std::string>& head) {
  std::string out = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!--\n";
  for (const std::string& h : head) out += "  " + xmlComment(h) + "\n";
  out += "-->\n<flowfacts>\n";
  for (const Fact& f : c.facts) {
    out += "  <loop source=\"" + xmlEscape(f.file) + "\" line=\"" + std::to_string(f.line) +
           "\" maxcount=\"" + std::to_string(f.bound) + "\"";
    // Extension attributes (FFX tools ignore attributes they do not know).
    out += " crosscheck-function=\"" + xmlEscape(join(f.functions, " ")) + "\"";
    out += " crosscheck-column=\"" + std::to_string(f.column) + "\"";
    if (!f.potential.empty()) out += " crosscheck-potential=\"" + xmlEscape(f.potential) + "\"";
    out += std::string(" crosscheck-certified=\"") + (f.certified ? "true" : "false") + "\"/>\n";
  }
  return out + "</flowfacts>\n";
}

std::string ais(const Collected& c, const std::vector<std::string>& head, bool v2) {
  std::string out;
  for (const std::string& h : head) out += "# " + oneLine(h) + "\n";
  out += "# Loops are designated by routine and number. aiT numbers the loops of a routine in the\n"
         "# executable; CrossCheck numbers them in source order. The two agree only if the compiler\n"
         "# keeps the loops of the function in that order and does not inline or unroll them:\n"
         "# compare with aiT's loop list before use. This file was not validated with aiT.\n";
  for (const Fact& f : c.facts) {
    out += "\n# " + oneLine(join(f.functions, ", ")) + ": " + f.file + ", line " + std::to_string(f.line) +
           (f.certified ? " (certified function)" : "") + "\n";
    if (v2)
      out += "loop " + aisString(f.symbol + ".L" + std::to_string(f.index)) + " { bound: 0 .. " +
             std::to_string(f.bound) + "; }\n";
    else
      out += "loop " + aisString(f.symbol) + " + " + std::to_string(f.index) + " loops max " +
             std::to_string(f.bound) + ";\n";
  }
  return out;
}

