std::string uriOf(const std::string& path, const std::string& base, bool& relative) {
  relative = false;
  std::string p = path;
  if (!base.empty()) {
    std::string b = base;
    if (b.back() != '/') b += '/';
    if (p.rfind(b, 0) == 0) {
      p = p.substr(b.size());
      relative = true;
    }
  }
  std::string out = (!relative && !p.empty() && p[0] == '/') ? "file://" : "";
  for (unsigned char ch : p) {
    if (std::isalnum(ch) || std::string("/-._~").find(static_cast<char>(ch)) != std::string::npos)
      out += static_cast<char>(ch);
    else {
      char buf[4];
      std::snprintf(buf, sizeof buf, "%%%02X", ch);
      out += buf;
    }
  }
  return out;
}

std::string location(const std::string& file, unsigned line, unsigned column, const std::string& base) {
  if (file.empty() || line == 0) return "";
  bool rel = false;
  std::string uri = uriOf(file, base, rel);
  std::string out = "\"locations\": [{\"physicalLocation\": {\"artifactLocation\": {\"uri\": " + jsonQuote(uri);
  if (rel) out += ", \"uriBaseId\": \"%SRCROOT%\"";
  out += "}, \"region\": {\"startLine\": " + std::to_string(line);
  if (column) out += ", \"startColumn\": " + std::to_string(column);
  return out + "}}}]";
}

struct Rule {
  const char* id;
  const char* level;
  const char* text;
};
const Rule rules[] = {
    {"rejected", "error", "Function rejected by the real-time profile, or without a cost bound"},
    {"deadline", "error", "Worst-case cost bound exceeds the declared deadline"},
    {"bound", "note", "Worst-case cost bound of a function (abstract units)"},
    {"assumption", "note", "Trusted assumption of a bound (annotation, contract, library cost)"},
};

std::string result(int rule, const std::string& message, const std::string& loc,
                   const std::string& properties = "") {
  std::string out = "{\"ruleId\": \"" + std::string(rules[rule].id) + "\", \"ruleIndex\": " +
                    std::to_string(rule) + ", \"level\": \"" + rules[rule].level +
                    "\", \"message\": {\"text\": " + jsonQuote(message) + "}";
  if (!loc.empty()) out += ", " + loc;
  if (!properties.empty()) out += ", \"properties\": {" + properties + "}";
  return out + "}";
}

