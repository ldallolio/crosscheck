"""Run crosscheck-tool on the C sources of CMSIS-DSP (Arm, Apache-2.0), an open-source
signal-processing library for Cortex-M real-time systems, and classify what the analysis
bounds and what blocks it.

CMSIS-DSP and the CMSIS 6 Core headers are fetched at pinned revisions into `.cache/`
(gitignored; nothing is vendored). Each source file is analysed for a Cortex-M4 target
(`--target=thumbv7em-none-eabi -mcpu=cortex-m4`, freestanding; minimal `string.h` and
`math.h` declarations are generated in `.cache/stubs/`), in two modes:

* as is: every function of the file, no annotation;
* with input ranges and context: the other files of the same group and the common tables
  are included after the file as definitions (calls into them have bodies, only the file's
  functions are analysed as roots), `memset`/`memcpy`/`memmove` get illustrative contracts
  (4 + 1 unit per byte, `.cache/contracts.json`), and the option `input-range=1,N` (N = --range, default 1024): every
  integer input without a declared range, parameters and the fields read through pointer
  parameters (`S->numTaps`), is assumed in [1, N] if unsigned and [-N, N] if signed. The
  library's sizes (`blockSize`, `numSamples`, ...) are parameters or instance fields, and a
  numeric bound needs their range; sizes of at least 1 are what the code assumes when it
  computes `blockSize - 1U`. This is an assumption of the run, listed in each report, not a
  statement about the library.

Usage (from the repository root, after building the plugin):

    python3 benchmarks/cmsis/run_cmsis.py [--extra-arg=...] [--only Dir/file.c] [--json out.json]
"""
import argparse
import collections
import json
import pathlib
import re
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DSP_REPO, DSP_REV = "https://github.com/ARM-software/CMSIS-DSP.git", "5a28089bb429d07774d8baeee03d475e232ad4a6"
CORE_REPO, CORE_REV = "https://github.com/ARM-software/CMSIS_6.git", "69b5aa343e618b74ffb40ca2b13f73a0cda7ab76"

STRING_H = """/* Minimal freestanding declarations for the analysis (generated by run_cmsis.py). */
#ifndef CROSSCHECK_STUB_STRING_H
#define CROSSCHECK_STUB_STRING_H
#include <stddef.h>
void *memcpy(void *d, const void *s, size_t n);
void *memset(void *d, int c, size_t n);
void *memmove(void *d, const void *s, size_t n);
int memcmp(const void *a, const void *b, size_t n);
size_t strlen(const char *s);
#endif
"""
MATH_H = """/* Minimal freestanding declarations for the analysis (generated by run_cmsis.py). */
#ifndef CROSSCHECK_STUB_MATH_H
#define CROSSCHECK_STUB_MATH_H
float sqrtf(float); double sqrt(double); float fabsf(float); double fabs(double);
float sinf(float); float cosf(float); float expf(float); float logf(float); float log2f(float);
float powf(float, float); float atan2f(float, float); float tanhf(float); float floorf(float);
double exp(double); double log(double); double log2(double); double pow(double, double);
double sin(double); double cos(double); double atan2(double, double); double floor(double);
float roundf(float); double round(double); float fmaxf(float, float); float fminf(float, float);
float ceilf(float); double ceil(double);
#define INFINITY (__builtin_inff())
#define NAN (__builtin_nanf(""))
#define M_PI 3.14159265358979323846
#endif
"""


CONTRACTS = """{"format": "crosscheck-contracts", "version": 1,
 "implementation": "illustrative costs for this run (4 + 1 per byte, abstract units), not measured",
 "contracts": [
  {"function": "memset", "cost": {"c": 4, "per_arg": {"2": 1}}},
  {"function": "memcpy", "cost": {"c": 4, "per_arg": {"2": 1}}},
  {"function": "memmove", "cost": {"c": 4, "per_arg": {"2": 1}}}
 ]}
"""


def fetch(cache: pathlib.Path):
    for name, repo, rev in (("cmsis-dsp", DSP_REPO, DSP_REV), ("cmsis6", CORE_REPO, CORE_REV)):
        d = cache / name
        if not d.exists():
            subprocess.run(["git", "clone", "--quiet", repo, str(d)], check=True)
        subprocess.run(["git", "-C", str(d), "fetch", "--quiet", "origin", rev], check=False)
        subprocess.run(["git", "-C", str(d), "checkout", "--quiet", rev], check=True)
    stubs = cache / "stubs"
    stubs.mkdir(exist_ok=True)
    (stubs / "string.h").write_text(STRING_H)
    (stubs / "math.h").write_text(MATH_H)
    (cache / "contracts.json").write_text(CONTRACTS)
    return cache / "cmsis-dsp", cache / "cmsis6", stubs


# A function definition: return type, name, parameters, then "{" (CMSIS style: one per line).
FUNC = re.compile(r"^(?P<head>[A-Za-z_][\w \*]*?\b(?P<name>arm_\w+)\s*\()(?P<params>[^;{)]*)\)\s*\{",
                  re.M | re.S)
INT_PARAM = re.compile(r"^\s*(?:const\s+)?(?P<type>u?int(?:8|16|32|64)_t|unsigned(?:\s+int)?|int|"
                       r"size_t|q7_t|q15_t|q31_t|q63_t)\s+(?P<name>[A-Za-z_]\w*)\s*$")
UNSIGNED = re.compile(r"^(?:uint\d+_t|unsigned|unsigned\s+int|size_t)$")


def harness(text: str, n: int) -> str:
    def params(m):
        ps = []
        for p in m.group("params").split(","):
            q = INT_PARAM.match(p)
            if q:
                lo = "0" if UNSIGNED.match(q.group("type")) else f"-{n}"
                p = f" CROSSCHECK_RANGE({lo}, {n}) " + p.strip()
            ps.append(p)
        return m.group("head") + ",".join(ps) + ") {"
    text = text.lstrip("\ufeff")  # some files start with a byte-order mark
    return "#include <crosscheck/attributes.hpp>\n" + FUNC.sub(params, text)


CATEGORIES = [
    ("loop bound", "cannot derive an iteration bound"),
    ("recursion", "recursion"),
    ("intrinsic or library call without definition", "no definition is available"),
    ("indirect call", "indirect call"),
    ("floating-point or other", ""),
]


def classify(errors):
    out = set()
    for e in errors:
        for name, key in CATEGORIES:
            if key and key in e:
                out.add(name)
                break
        else:
            out.add("other: " + re.sub(r"'[^']*'", "'…'", e.split(": ", 1)[-1])[:60])
    return out


def unit_for(src, dsp, work):
    """`src` followed by the other files of its group and the common tables, as included
    definitions: calls into them have bodies, and only `src`'s functions are roots."""
    group = src.parent
    # The common tables: the two files that define them once (the others are variants
    # of the same tables for other configurations).
    tables = [dsp / "Source/CommonTables" / n for n in ("arm_common_tables.c", "arm_const_structs.c")]
    others = [f for f in sorted(group.glob("*.c")) + tables
              if f != src and not re.search(r"Functions(F16)?\.c$", f.name) and not f.name.startswith("_")]
    unit = work / (src.stem + ".unit.c")
    unit.write_text(src.read_text(errors="replace").lstrip("\ufeff") + "\n" +
                    "".join(f'#include "{f}"\n' for f in others))
    return unit


def run(tool, src, mode, flags, work, n, dsp=None, contracts=None):
    work.mkdir(parents=True, exist_ok=True)
    stem = src.stem + "." + mode
    report = work / (stem + ".json")
    report.unlink(missing_ok=True)
    opts = [f"--opt=input-range=1,{n}", f"--opt=contracts={contracts}"] if mode == "ranges" else []
    lang = ["-x", "c", "-std=gnu11"]
    unit = unit_for(src, dsp, work) if mode == "ranges" else src
    cmd = [str(tool), "--all", f"--report={report}", *opts, str(unit), "--", *lang, *flags]
    t0 = time.monotonic()
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
        empty = not report.exists() or not json.loads(report.read_text()).get("functions")
        if empty and mode == "ranges":  # the group does not compile as one unit
            cmd[cmd.index(str(unit))] = str(src)
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    except subprocess.TimeoutExpired:
        return None, 300.0, "timeout"
    if not report.exists():
        first = next((l for l in p.stderr.splitlines() if "error:" in l), p.stderr[-200:])
        return None, time.monotonic() - t0, first
    return json.loads(report.read_text()), time.monotonic() - t0, ""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tool", default=str(ROOT / "clang-plugin/build/crosscheck-tool"))
    ap.add_argument("--cache", default=str(HERE / ".cache"))
    ap.add_argument("--extra-arg", action="append", default=[])
    ap.add_argument("--only", action="append", help="run only these files (relative to Source/)")
    ap.add_argument("--range", type=int, default=1024)
    ap.add_argument("--json")
    a = ap.parse_args()
    dsp, core, stubs = fetch(pathlib.Path(a.cache))
    flags = ["-w", "--target=thumbv7em-none-eabi", "-mcpu=cortex-m4", "-mfloat-abi=hard",
             "-mfpu=fpv4-sp-d16", "-ffreestanding", "-DARM_MATH_CM4", f"-I{stubs}",
             f"-I{dsp / 'Include'}", f"-I{dsp / 'PrivateInclude'}", f"-I{core / 'CMSIS/Core/Include'}",
             f"-I{ROOT / 'clang-plugin/include'}", *a.extra_arg]
    files = sorted((dsp / "Source").rglob("*.c"))
    # The "*Functions.c" / "*FunctionsF16.c" files only #include the others.
    files = [f for f in files if not re.search(r"Functions(F16)?\.c$", f.name) and not f.name.startswith("_")]
    if a.only:
        files = [f for f in files if str(f.relative_to(dsp / "Source")) in a.only]
    rows = []
    work = pathlib.Path(a.cache) / "work"
    for f in files:
        rel = str(f.relative_to(dsp / "Source"))
        row = dict(file=rel, group=rel.split("/")[0])
        for mode in ("as-is", "ranges"):
            rep, secs, fail = run(a.tool, f, mode, flags, work, a.range, dsp, pathlib.Path(a.cache) / "contracts.json")
            fns = [] if rep is None else [x for x in rep["functions"] if x["name"].startswith("arm_")]
            row[mode] = dict(
                parsed=rep is not None, failure=fail, seconds=round(secs, 1),
                functions=len(fns), bounded=sum(1 for x in fns if x["ok"]),
                loops=sum(len(x["loops"]) for x in fns),
                loops_bounded=sum(1 for x in fns for l in x["loops"] if l.get("verified")),
                blockers=sorted(set().union(*[classify(x["errors"]) for x in fns if not x["ok"]] or [set()])),
                names=[x["name"] for x in fns if x["ok"]])
        rows.append(row)
        r = row["ranges"]
        print(f"{rel:60s} as-is {row['as-is']['bounded']}/{row['as-is']['functions']}  "
              f"ranges {r['bounded']}/{r['functions']}  {', '.join(r['blockers'])[:80]}", file=sys.stderr)
    for mode in ("as-is", "ranges"):
        parsed = sum(r[mode]["parsed"] for r in rows)
        fns = sum(r[mode]["functions"] for r in rows)
        ok = sum(r[mode]["bounded"] for r in rows)
        loops = sum(r[mode]["loops"] for r in rows)
        lb = sum(r[mode]["loops_bounded"] for r in rows)
        print(f"{mode}: {len(rows)} files, {parsed} analysed, {fns} functions, {ok} bounded; "
              f"{loops} loops, {lb} with a derived bound")
        blockers = collections.Counter(b for r in rows for b in r[mode]["blockers"])
        for b, c in blockers.most_common(12):
            print(f"  {c:4d} files: {b}")
        failures = collections.Counter(re.sub(r"^.*error: ", "", r[mode]["failure"])[:70]
                                       for r in rows if not r[mode]["parsed"])
        for b, c in failures.most_common(5):
            print(f"  {c:4d} files not analysed: {b}")
    if a.json:
        pathlib.Path(a.json).write_text(json.dumps(dict(dsp=DSP_REV, core=CORE_REV, rows=rows), indent=1) + "\n")


if __name__ == "__main__":
    main()
